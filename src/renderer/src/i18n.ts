const dictionaries: Record<Lang, Dict> = { en, ru }

export function translate(lang: Lang, key: string, params?: Record<string, string | number>): string {
  const dict = dictionaries[lang] ?? en
  let value = dict[key] ?? en[key] ?? key
  if (params) {
    for (const [name, replacement] of Object.entries(params)) {
      value = value.replace(new RegExp(`\\{${name}\\}`, 'g'), String(replacement))
    }
  }
  return value
}

export function formatNumber(value: number, lang: Lang): string {
  return new Intl.NumberFormat(lang === 'ru' ? 'ru-RU' : 'en-US').format(value)
}

export function formatDateTime(timestamp: number, lang: Lang): string {
  return new Date(timestamp).toLocaleString(lang === 'ru' ? 'ru-RU' : 'en-US', {
    day: 'numeric',
    month: 'short',
    hour: '2-digit',
    minute: '2-digit'
  })
}
